/*
 * Purpose: verify XER retains its decoder state across every byte split.
 * Original source: issue #583's canonical XER golden representation.
 * Version/date: 2026-10-21.
 * Inputs: no parameters.
 * Returns: no value.
 * Exceptions: assertions abort if a partial document succeeds or resumed
 *             decoding loses bytes; partial values are always freed.
 * Responsible party: asn1c maintainers.
 * History: added to cover chunked transparent-group XML decoding.
 * Example: check_xer_splits();
 */
static void
check_xer_splits(void) {
    static const char xml[] =
        "<Rec><id>1</id><before><true/></before><g1>3</g1><after>2</after></Rec>";
    size_t split;

    for(split = 0; split <= sizeof(xml) - 1; split++) {
        Rec_t *decoded = NULL;
        asn_dec_rval_t first = xer_decode(NULL, &asn_DEF_Rec,
                (void **)&decoded, xml, split);
        if(split < sizeof(xml) - 1) assert(first.code == RC_WMORE);
        assert(first.consumed <= split);
        if(first.code == RC_WMORE) {
            size_t consumed = first.consumed;
            asn_dec_rval_t second = xer_decode(NULL, &asn_DEF_Rec,
                    (void **)&decoded, xml + consumed,
                    sizeof(xml) - 1 - consumed);
            assert(second.code == RC_OK);
            assert(consumed + second.consumed == sizeof(xml) - 1);
            assert_rec_value(decoded);
        } else if(split == sizeof(xml) - 1) {
            assert(first.code == RC_OK);
            assert(first.consumed == sizeof(xml) - 1);
            assert_rec_value(decoded);
        }
        if(decoded != NULL) ASN_STRUCT_FREE(asn_DEF_Rec, decoded);
    }
}

